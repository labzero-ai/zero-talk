/// The plain ASCII spelling of `w` (José: Jose, naïve: naive, Straße: Strasse), or None when `w` is ASCII already or has a non-ASCII character that
/// is not in the table (a letter of another script, a symbol): such a word is left as it is. A letter that expands (ß, Æ, Þ) is capitalized
/// like its word: all upper case in an all-capitals word, else only its first letter.
pub fn fold_word(w: &str) -> Option<String> {
    if w.is_ascii() {
        return None;
    }
    let has_lower = w.chars().any(char::is_lowercase);
    let mut out = String::with_capacity(w.len());
    for c in w.chars() {
        if c.is_ascii() {
            out.push(c);
            continue;
        }
        let i = FOLD.binary_search_by_key(&c, |e| e.0).ok()?;
        let spelling = &FOLD[i].1;
        let s = std::str::from_utf8(&spelling[..spelling.iter().position(|&b| b == 0).unwrap_or(3)]).unwrap();
        if has_lower && s.len() > 1 && c.is_uppercase() {
            out.push_str(&s[..1]);
            out.push_str(&s[1..].to_lowercase());
        } else {
            out.push_str(s);
        }
    }
    Some(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn accents_fold_to_the_plain_spelling() {
        for (w, f) in [("José", "Jose"), ("café", "cafe"), ("naïve", "naive"), ("Zürich", "Zurich"), ("Dvořák", "Dvorak"), ("Straße", "Strasse"), ("STRAẞE", "STRASSE"),
                       ("Æsop", "Aesop"), ("ÆSOP", "AESOP"), ("Łódź", "Lodz"), ("ﬁnance", "finance"), ("ＡＢＣ", "ABC"), ("Nguyễn", "Nguyen"), ("José's", "Jose's")] {
            assert_eq!(fold_word(w).as_deref(), Some(f), "{w}");
        }
    }

    #[test]
    fn other_words_are_left_alone() {
        for w in ["cafe", "Москва", "東京", "Αθήνα", "café→", "Zürich★", ""] {
            assert_eq!(fold_word(w), None, "{w}");
        }
    }

    #[test]
    fn the_table_is_sorted_and_folds_to_ascii_letters() {
        assert!(FOLD.windows(2).all(|p| p[0].0 < p[1].0));
        assert!(FOLD.iter().all(|e| !e.0.is_ascii() && e.1[0].is_ascii_alphabetic() && e.1.iter().all(|&b| b == 0 || b.is_ascii_alphabetic())));
    }
}
