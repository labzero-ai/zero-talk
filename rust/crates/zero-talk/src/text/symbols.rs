pub fn is_icon(c: char) -> bool {
    let cp = c as u32;
    match ICONS.binary_search_by(|&(lo, hi)| if cp < lo { std::cmp::Ordering::Greater } else if cp > hi { std::cmp::Ordering::Less } else { std::cmp::Ordering::Equal }) {
        Ok(_) => true,
        Err(_) => false,
    }
}
